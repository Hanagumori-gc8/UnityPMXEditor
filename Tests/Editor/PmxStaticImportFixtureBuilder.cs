        public static byte[] Build(string texturePath = "texture.png")
        {
            using (var stream = new MemoryStream())
            using (var writer = new BinaryWriter(stream, Encoding.UTF8, true))
            {
                WriteHeader(writer);
                WriteText(writer, "Static Fixture");
                WriteText(writer, "Static Fixture");
                WriteText(writer, "Generated by UnityPMXEditor tests");
                WriteText(writer, "Generated by UnityPMXEditor tests");

                writer.Write(4);
                WriteVertex(writer, 0, 0, 0, 0, 0);
                WriteVertex(writer, 1, 0, 0, 1, 0);
                WriteVertex(writer, 0, 1, 0, 0, 1);
                WriteVertex(writer, 1, 1, 0, 1, 1);

                writer.Write(6);
                writer.Write((byte)0);
                writer.Write((byte)1);
                writer.Write((byte)2);
                writer.Write((byte)1);
                writer.Write((byte)3);
                writer.Write((byte)2);

                writer.Write(1);
                WriteText(writer, texturePath);

                writer.Write(2);
                WriteMaterial(writer, 0, 3);
                WriteMaterial(writer, -1, 3);

                WriteSingleBone(writer);
                writer.Write(0); // Morph count
                writer.Write(0); // DisplayFrame count
                writer.Write(0); // RigidBody count
                writer.Write(0); // Joint count; PMX 2.0 ends here
                writer.Flush();
                return stream.ToArray();
            }
        }

        public static byte[] BuildLargeVertexFixture(int vertexCount)
        {
            if (vertexCount <= 65535) throw new ArgumentOutOfRangeException(nameof(vertexCount));
            using (var stream = new MemoryStream())
            using (var writer = new BinaryWriter(stream, Encoding.UTF8, true))
            {
                WriteHeader(writer);
                WriteText(writer, "Large Fixture");
                WriteText(writer, "Large Fixture");
                WriteText(writer, string.Empty);
                WriteText(writer, string.Empty);
                writer.Write(vertexCount);
                for (int i = 0; i < vertexCount; i++) WriteVertex(writer, 0, 0, 0, 0, 0);
                writer.Write(0); // Surface index count
                writer.Write(0); // Texture count
                writer.Write(1); // Material count
                WriteMaterial(writer, -1, 0);
                WriteSingleBone(writer);
                writer.Write(0);
                writer.Write(0);
                writer.Write(0);
                writer.Write(0);
                writer.Flush();
                return stream.ToArray();
            }
        }

