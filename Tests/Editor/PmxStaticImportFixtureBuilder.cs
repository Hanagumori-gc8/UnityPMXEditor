        private static void WriteHeader(BinaryWriter writer, float version = 2.0f)
        {
            writer.Write(new byte[] { 0x50, 0x4D, 0x58, 0x20 });
            writer.Write(version);
            writer.Write((byte)8);
            writer.Write((byte)1); // UTF-8
            writer.Write((byte)0); // Additional UV count
            for (int i = 0; i < 6; i++) writer.Write((byte)1);
        }

        private static void WriteVertex(BinaryWriter writer, float x, float y, float z, float u, float v)
        {
            WriteVector3(writer, x, y, z);
            WriteVector3(writer, 0, 0, 1);
            writer.Write(u);
            writer.Write(v);
            writer.Write((byte)0); // BDEF1
            writer.Write((sbyte)0);
            writer.Write(1f);
        }

        private static void WriteBdef1Vertex(BinaryWriter writer, float x, float y, int bone)
        {
            WriteVertexPrefix(writer, x, y);
            writer.Write((byte)PmxVertexWeightType.Bdef1);
            writer.Write(unchecked((sbyte)bone));
            writer.Write(1f);
        }

        private static void WriteBdef2Vertex(BinaryWriter writer, float x, float y,
            int bone0, int bone1, float weight0)
        {
            WriteVertexPrefix(writer, x, y);
            writer.Write((byte)PmxVertexWeightType.Bdef2);
            writer.Write(unchecked((sbyte)bone0));
            writer.Write(unchecked((sbyte)bone1));
            writer.Write(weight0);
            writer.Write(1f);
        }

        private static void WriteBdef4Vertex(BinaryWriter writer, float x, float y,
            int[] bones, float[] weights)
        {
            WriteVertexPrefix(writer, x, y);
            writer.Write((byte)PmxVertexWeightType.Bdef4);
            for (int i = 0; i < 4; i++) writer.Write(unchecked((sbyte)bones[i]));
            for (int i = 0; i < 4; i++) writer.Write(weights[i]);
            writer.Write(1f);
        }

        private static void WriteAdvancedVertex(BinaryWriter writer, PmxVertexWeightType type)
        {
            WriteVertexPrefix(writer, 0, 0);
            writer.Write((byte)type);
            if (type == PmxVertexWeightType.Sdef)
            {
                writer.Write((sbyte)0);
                writer.Write((sbyte)1);
                writer.Write(0.5f);
                WriteVector3(writer, 1, 2, 3);
                WriteVector3(writer, 4, 5, 6);
                WriteVector3(writer, 7, 8, 9);
            }
            else
            {
                writer.Write((sbyte)0);
                writer.Write((sbyte)1);
                writer.Write((sbyte)-1);
                writer.Write((sbyte)-1);
                writer.Write(0.5f);
                writer.Write(0.5f);
                writer.Write(0f);
                writer.Write(0f);
            }
            writer.Write(1f);
        }

        private static void WriteVertexPrefix(BinaryWriter writer, float x, float y)
        {
            WriteVector3(writer, x, y, 0);
            WriteVector3(writer, 0, 0, 1);
            writer.Write(x + 0.5f);
            writer.Write(y + 0.5f);
        }

